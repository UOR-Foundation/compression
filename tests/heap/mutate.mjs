// Plant one count-overflow defect in a prepared diagnostic copy, never in product source.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const target=path.resolve(process.argv[2]??'');
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
if(!process.argv[2] || target===repo || target.startsWith(repo+path.sep)) throw Error('use a separate prepared diagnostic copy');
const relative='src/Uorc/Core/Heap.lex.tex', file=path.join(target,relative);
const control=await fs.readFile(file,'utf8');
const inventory=JSON.parse(await fs.readFile(path.join(target,'source-inventory.json'),'utf8'));
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
if(inventory.sources.find(s=>s.path===relative)?.sha256!==sha(control)) throw Error('control source inventory mismatch');
const needle='prim checked_add (project entry incoming) (1 : UInt64)';
if(control.split(needle).length!==2) throw Error('missing or ambiguous exact mutation site');
const mutant=control.replace(needle,'prim checked_add (project entry incoming) (0 : UInt64)');
await fs.writeFile(file,mutant);
const receipt={schema:'uorc/heap-mutation/1',file:relative,owner:'Uorc.Uorc.Core.HeapTests.conformance_negative_countOverflow',defect:'retain increments incoming count by zero, allowing incoming-count overflow to pass',controlSha256:sha(control),mutantSha256:sha(mutant)};
await fs.writeFile(path.join(target,'mutation.json'),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(receipt));
