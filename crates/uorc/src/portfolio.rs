//! The strategy portfolio (`Uorc.Client.portfolio`): how the encoder picks
//! the coding of a frame.
//!
//! A strategy is a point of the codec space: a transform (none, or the x86
//! branch filter), an ncm model profile, and a model state (none, or one of
//! the κ-named states of the basis, [`crate::states`]). A frame's family
//! comes from cheap statistics of its bytes ([`family`]). Every (family,
//! strategy) pair carries a bounded integer weight in 1..=16; the schedule of
//! a family is every strategy ordered by weight (ties by portfolio order), so
//! no strategy is ever unreachable. The encoder codes every strategy of the
//! schedule the frame can code, in schedule order, and after them each
//! strategy of the family's v0.4 pair ([`V04_PAIR`]) the table does not
//! hold, and keeps the least
//! archive in bytes, then in decode steps (raw when that is smaller). The
//! coded strategies always include the ones v0.4 coded for the family, and
//! every strategy without a state learns its context mask, so no frame is
//! coded larger than v0.4 coded it, whatever the weights.
//!
//! The portfolio is data, a [`Table`] of strategy entries and weights in the
//! byte form the model's `compress` reads. The shipped table ([`SHIPPED`],
//! `weights.rs`) is generated by the engine (`Uorc.Engine`, `crates/engine`)
//! from `model/engine.toml`: each tick decides "candidate dominates incumbent
//! on family f" over a κ-named corpus and consolidates the winners into these
//! weights. Any table is safe: an entry the coder cannot apply is skipped,
//! and every candidate decodes to the frame. The output is a function of the
//! input and the table alone, whatever `--threads` is.

use crate::ncm;
use crate::weights;

/// A way to code a frame: over the x86 filter or not, the ncm profile, and
/// the model state the frame continues (0 for none, `i` for state `i`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Strategy {
    /// Coded over the x86 branch filter.
    pub x86: bool,
    /// The ncm model profile.
    pub profile: u32,
    /// The κ-named model state the frame continues (0: none).
    pub state: u8,
}

/// Every ncm feature but the match-state mixer selection: the profile that
/// short inputs favour.
pub const MID: u32 = ncm::FULL & !ncm::F_SEL;

/// Bytes of one strategy entry: the u32 little-endian word, then the state.
pub const ENTRY: usize = 5;

/// The word's x86 filter bit.
pub const X86_BIT: u32 = 1 << 31;

/// Families: tiny (< 4 KiB), small (< 64 KiB), x86 code (any size), text, other.
pub const FAMILIES: usize = 5;

/// The families' names, in order.
pub const FAMILY_NAMES: [&str; FAMILIES] = ["tiny", "small", "x86", "text", "other"];

/// The most strategies the encoder codes for a frame under the shipped
/// table: every entry, and the two of the family's v0.4 pair.
pub const MAX_PLAN: usize = SHIPPED_COUNT + 2;

const fn plain(x86: bool, profile: u32) -> Strategy {
    Strategy {
        x86,
        profile,
        state: 0,
    }
}

/// The two strategies v0.4 coded for each family (`Client.v04Pair`): tiny
/// V03 and FULL, small V03 and MID, x86 MID over the filter and FULL, text
/// and other FULL and MID. The encoder always codes them, so "no frame larger
/// than v0.4" follows from keeping the least of a superset of v0.4's trials.
pub const V04_PAIR: [[Strategy; 2]; FAMILIES] = [
    [plain(false, ncm::V03), plain(false, ncm::FULL)],
    [plain(false, ncm::V03), plain(false, MID)],
    [plain(true, MID), plain(false, ncm::FULL)],
    [plain(false, ncm::FULL), plain(false, MID)],
    [plain(false, ncm::FULL), plain(false, MID)],
];

/// A portfolio: strategy entries and one weight per (family, strategy).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Table<'a> {
    /// [`ENTRY`] bytes per strategy.
    pub strategies: &'a [u8],
    /// `FAMILIES * count` weights, row by family.
    pub weights: &'a [u8],
}

/// The portfolio the client ships.
pub const SHIPPED: Table<'static> = Table {
    strategies: &weights::STRATEGIES,
    weights: &weights::WEIGHTS,
};

impl Strategy {
    /// The entry's word: the profile, and bit 31 for the x86 filter.
    pub fn word(self) -> u32 {
        self.profile | if self.x86 { X86_BIT } else { 0 }
    }

    /// The [`ENTRY`] bytes of this strategy.
    pub fn entry(self) -> [u8; ENTRY] {
        let w = self.word().to_le_bytes();
        [w[0], w[1], w[2], w[3], self.state]
    }
}

impl<'a> Table<'a> {
    /// Strategy entries in the table.
    pub fn count(&self) -> usize {
        self.strategies.len() / ENTRY
    }

    /// Entry `i`, when the coder can apply it: a valid profile word, no other
    /// word bits, and no state or one the basis has.
    pub fn strategy(&self, i: usize) -> Option<Strategy> {
        let e = self.strategies.get(i * ENTRY..(i + 1) * ENTRY)?;
        let word = u32::from_le_bytes([e[0], e[1], e[2], e[3]]);
        let profile = word & !X86_BIT;
        let state = e[4];
        (ncm::valid_profile(profile) && (state == 0 || crate::states::state(state).is_some()))
            .then_some(Strategy {
                x86: word & X86_BIT != 0,
                profile,
                state,
            })
    }

    /// The weight of strategy `i` for `family` (0 when the table has none).
    pub fn weight(&self, family: usize, i: usize) -> u8 {
        self.weights
            .get(family * self.count() + i)
            .copied()
            .unwrap_or(0)
    }

    /// Every strategy index, ordered by its weight for `family` (highest
    /// first, ties in portfolio order): a permutation of the entries.
    pub fn schedule(&self, family: usize) -> Vec<usize> {
        let mut s: Vec<usize> = (0..self.count()).collect();
        // stable, so equal weights keep portfolio order
        s.sort_by_key(|&i| std::cmp::Reverse(self.weight(family, i)));
        s
    }

    /// The strategies the encoder codes for `frame`, in order
    /// (`Client.planned`): every scheduled entry (an entry the coder cannot
    /// apply yields no candidate), then each strategy of the family's
    /// [`V04_PAIR`] whose entry bytes no entry has.
    pub fn plan(&self, frame: &[u8]) -> Vec<Option<Strategy>> {
        let f = family(frame);
        let scheduled: Vec<usize> = self.schedule(f);
        let entry = |i: usize| &self.strategies[i * ENTRY..(i + 1) * ENTRY];
        let mut plan: Vec<Option<Strategy>> = scheduled.iter().map(|&i| self.strategy(i)).collect();
        for s in V04_PAIR[f] {
            if !scheduled.iter().any(|&i| entry(i) == s.entry()) {
                plan.push(Some(s));
            }
        }
        plan
    }
}

/// Entries in the shipped table.
const SHIPPED_COUNT: usize = weights::STRATEGIES.len() / ENTRY;

/// The shipped table's strategies, in table order.
pub const STRATEGIES: [Strategy; SHIPPED_COUNT] = {
    let mut out = [plain(false, 0); SHIPPED_COUNT];
    let mut i = 0;
    while i < SHIPPED_COUNT {
        let e = &weights::STRATEGIES;
        let word = u32::from_le_bytes([
            e[i * ENTRY],
            e[i * ENTRY + 1],
            e[i * ENTRY + 2],
            e[i * ENTRY + 3],
        ]);
        out[i] = Strategy {
            x86: word & X86_BIT != 0,
            profile: word & !X86_BIT,
            state: e[i * ENTRY + 4],
        };
        i += 1;
    }
    out
};

/// The strategies the client codes for `frame` under the shipped table, in
/// plan order (see [`Table::plan`]).
pub fn plan(frame: &[u8]) -> Vec<Strategy> {
    SHIPPED.plan(frame).into_iter().flatten().collect()
}

/// The rule30 learning rule: a success adds 2 up to 16, a failure takes 1
/// down to 1.
pub const fn learn(w: u8, success: bool) -> u8 {
    if success {
        if w + 2 <= 16 {
            w + 2
        } else {
            16
        }
    } else if w >= 2 {
        w - 1
    } else {
        1
    }
}

/// The family of a frame: x86 code ([`crate::x86::dense`], at any size, so
/// a small executable still reaches the filter), then tiny below 4 KiB,
/// small below 64 KiB, text (at least 90% of the bytes are tab, line feed,
/// carriage return or printable ASCII), else other.
pub fn family(frame: &[u8]) -> usize {
    let n = frame.len();
    if crate::x86::dense(frame) {
        2
    } else if n < 4096 {
        0
    } else if n < 65536 {
        1
    } else if 10 * printable(frame) >= 9 * n {
        3
    } else {
        4
    }
}

fn printable(frame: &[u8]) -> usize {
    frame
        .iter()
        .filter(|&&b| b == 9 || b == 10 || b == 13 || (32..127).contains(&b))
        .count()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn learning_stays_bounded_and_schedules_are_permutations() {
        for w in 1..=16 {
            assert!((1..=16).contains(&learn(w, true)));
            assert!((1..=16).contains(&learn(w, false)));
        }
        assert_eq!(SHIPPED.weights.len(), FAMILIES * SHIPPED.count());
        for f in 0..FAMILIES {
            let mut s = SHIPPED.schedule(f);
            for k in 1..s.len() {
                assert!(SHIPPED.weight(f, s[k - 1]) >= SHIPPED.weight(f, s[k]));
            }
            s.sort_unstable();
            assert_eq!(s, (0..SHIPPED.count()).collect::<Vec<_>>());
            assert!(
                SHIPPED.weights[f * SHIPPED.count()..(f + 1) * SHIPPED.count()]
                    .iter()
                    .all(|w| (1..=16).contains(w))
            );
        }
    }

    #[test]
    fn the_shipped_entries_extend_the_v04_portfolio() {
        let v04 = [ncm::FULL, MID, ncm::V03]
            .into_iter()
            .flat_map(|profile| [false, true].map(|x86| plain(x86, profile)));
        for (i, s) in v04.enumerate() {
            assert_eq!(SHIPPED.strategy(i), Some(s));
            assert_eq!(SHIPPED.strategies[i * ENTRY..(i + 1) * ENTRY], s.entry());
        }
        // every further entry continues a state of the basis
        for i in 6..SHIPPED.count() {
            assert!(
                SHIPPED.strategy(i).is_some_and(|s| s.state > 0),
                "entry {i}"
            );
        }
    }

    /// Every plan holds the family's v0.4 pair, whatever the weights, and
    /// codes no entry twice.
    #[test]
    fn every_plan_holds_the_v04_pair() {
        let frames: [Vec<u8>; FAMILIES] = [
            vec![b'a'; 100],
            vec![b'a'; 10_000],
            (0..400u32)
                .flat_map(|k| [0xE8, (k % 200) as u8, 0, 0, 0, 0x90])
                .collect(),
            vec![b'a'; 100_000],
            vec![0; 100_000],
        ];
        let flat = [1u8; 6 * FAMILIES];
        let tables = [
            SHIPPED,
            Table {
                strategies: &weights::STRATEGIES[..6 * ENTRY],
                weights: &flat,
            },
        ];
        for t in tables {
            for (f, frame) in frames.iter().enumerate() {
                assert_eq!(family(frame), f);
                let plan = t.plan(frame);
                assert!(plan.len() <= MAX_PLAN);
                for s in V04_PAIR[f] {
                    assert!(plan.contains(&Some(s)), "family {f}: {s:?}");
                }
                let coded: Vec<_> = plan.iter().flatten().collect();
                for (k, s) in coded.iter().enumerate() {
                    assert!(!coded[..k].contains(s), "family {f}: {s:?} twice");
                }
            }
        }
    }

    #[test]
    fn an_entry_the_coder_cannot_apply_is_skipped() {
        // a context table field of 1 bit (below ncm::TABLE_MIN), then an unnamed state
        let bad = Table {
            strategies: &[0xff, 0xff, 0x1f, 0x00, 0x00, 0xff, 0xff, 0x0f, 0x00, 0xee],
            weights: &[1; 10],
        };
        assert_eq!(bad.strategy(0), None);
        assert_eq!(bad.strategy(1), None);
        assert_eq!(bad.strategy(2), None);
        // the skipped entries keep their place; the v0.4 pair follows
        let plan = bad.plan(&[0; 10]);
        assert_eq!(plan[..2], [None, None]);
        assert_eq!(plan[2..], V04_PAIR[0].map(Some));
    }

    #[test]
    fn families() {
        assert_eq!(family(&[0; 100]), 0);
        assert_eq!(family(&[b'a'; 10_000]), 1);
        assert_eq!(family(&[b'a'; 100_000]), 3);
        assert_eq!(family(&[0; 100_000]), 4);
        // x86 code is x86 at any size, so a small executable tries the filter
        let calls: Vec<u8> = (0..400u32)
            .flat_map(|k| [0xE8, (k % 200) as u8, 0, 0, 0, 0x90])
            .collect();
        assert!(calls.len() < 4096);
        assert_eq!(family(&calls), 2);
    }
}
