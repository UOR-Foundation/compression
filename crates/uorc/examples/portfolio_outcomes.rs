//! Regenerates `src/portfolio-outcomes.tsv`, the measured outcomes the
//! portfolio's weight table is learned from (`portfolio::WEIGHTS`, checked by
//! the test `weights_are_learned_from_the_outcomes`):
//!
//! ```text
//! cargo run --release -p uorc --example portfolio_outcomes -- FILE... > crates/uorc/src/portfolio-outcomes.tsv
//! ```
//!
//! Each file is one training frame (at most `uorc::FRAME` bytes are read).
//! Lines are sorted by file name, so the order the table learns in is fixed;
//! after regenerating, update `WEIGHTS` to what the test reports.
use uorc::{archive, ncm, portfolio, states, x86};

fn main() {
    let mut files: Vec<String> = std::env::args().skip(1).collect();
    files.sort_by_key(|f| {
        std::path::Path::new(f)
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
    });
    println!("# uorc strategy portfolio training outcomes: one frame per line.");
    println!("# Columns: frame length, family, then the archive length of each strategy in portfolio order");
    println!("# (FULL, MID, V03, FULL over x86, MID over x86, V03 over x86, FULL from state 1, MID from state 1);");
    println!("# the frame length + 100 when the coder declined.");
    println!("# Generated by crates/uorc/examples/portfolio_outcomes.rs.");
    println!("# Training set: describe it here; files sorted by name.");
    let next = std::sync::atomic::AtomicUsize::new(0);
    let mut rows = vec![String::new(); files.len()];
    let slots: Vec<std::sync::Mutex<&mut String>> =
        rows.iter_mut().map(std::sync::Mutex::new).collect();
    std::thread::scope(|s| {
        for _ in 0..uorc::default_threads() {
            s.spawn(|| loop {
                let i = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                let Some(f) = files.get(i) else { break };
                **slots[i].lock().expect("slot") = outcome(f);
            });
        }
    });
    for r in rows {
        println!("{r}");
    }
}

/// One training line for the frame `f`: the archive length of each strategy.
fn outcome(f: &str) -> String {
    let mut d = std::fs::read(f).expect("readable file");
    d.truncate(uorc::FRAME);
    let n = d.len();
    let lengths = [n as u64];
    let declined = n + 100;
    let sizes: Vec<String> = portfolio::STRATEGIES
        .iter()
        .map(|st| {
            let archive = match states::state(st.state) {
                Some(s) => {
                    let (data, from) = if st.x86 {
                        (
                            x86::filter(&d, false, s.len() as u64).0,
                            x86::filter(s, false, 0).0,
                        )
                    } else {
                        (d.clone(), s.to_vec())
                    };
                    let id = states::identity(st.state).expect("state");
                    ncm::encode_warm(&from, &data, st.profile)
                        .and_then(|p| archive::state_archive(st.x86, st.profile, &id, &lengths, &p))
                }
                None => {
                    let data = if st.x86 {
                        x86::filter(&d, false, 0).0
                    } else {
                        d.clone()
                    };
                    let codec = if st.x86 {
                        archive::Codec::NcmX86
                    } else {
                        archive::Codec::Ncm
                    };
                    ncm::encode_profile(&[], &data, st.profile).and_then(|p| {
                        archive::linked_archive_profile(codec, st.profile, &lengths, &p)
                    })
                }
            };
            archive
                .map_or(declined, |a| a.len().min(declined))
                .to_string()
        })
        .collect();
    format!("{n}\t{}\t{}", portfolio::family(&d), sizes.join("\t"))
}
