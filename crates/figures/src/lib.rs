    fn values_are_base_ten_without_suffix_or_separators() {
        let s = sites("const A: u32 = 0x10; const B: usize = 131_072usize; const C: f64 = 2.5;");
        let v: Vec<_> = s.sites.iter().map(|s| s.value.as_str()).collect();
        assert_eq!(v, ["16", "131072", "2.5"]);
    }

