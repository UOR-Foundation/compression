/// What a check of the implementation against the register finds.
#[derive(Debug, Default)]
pub struct Outcome {
    /// Sites the register does not admit, and binding or tag errors: the
    /// change is rejected.
    pub rejected: Vec<String>,
    /// The register lists what the implementation no longer holds (or
    /// attributes differently): rewrite it with `just figures-write`.
    pub stale: Vec<String>,
    /// The implementation's entries.
    pub entries: Vec<Entry>,
    /// The scan.
    pub scan: Scan,
}

const RULE: &str = "A number in uorc's implementation is a facet derived from the input and the declared host (Uorc.Performance), \
a format identity the wire model states (a constant documented `Model: Uorc.Wire.<module>.<definition>`), or an identity (0, 1). \
Derive the figure from what it depends on; do not fix it.";

/// Check the implementation under `root` against `register` (None: no
/// register yet).
pub fn check(root: &Path, register: Option<&Register>) -> Result<Outcome, Error> {
    let dirs = scope(root)?;
    let mut scan = scan(root, &dirs)?;
    let graph: serde_json::Value =
        serde_json::from_str(&read(root, GRAPH)?).map_err(|e| format!("{GRAPH}: {e}"))?;
    let reach = sources::reach(&graph);
    for f in sources::page_files(root, &reach.page_dirs, &mut scan)? {
        let text = read(root, &f)?;
        sources::scan_js(&f, &text, &mut scan);
    }
    for (module, path) in sources::model_modules(root, &reach)? {
        let text = read(root, &path)?;
        sources::scan_lean(&path, &module, &text, &mut scan);
    }
    let mut out = Outcome {
        entries: entries(&scan),
        scan,
        ..Outcome::default()
    };
    let known = facets(&read(root, PERFORMANCE)?);
    for e in &out.entries {
        if let Some(f) = &e.facet {
            if !known.contains(f) {
                out.rejected.push(format!(
                    "{} {}: `Facet: {f}` names no Facet record of Uorc.Performance",
                    e.file, e.item
                ));
            }
        }
    }
    for b in &out.scan.bindings {
        match wire_value(root, &b.target) {
            Err(e) => out.rejected.push(format!("{} {}: {e}", b.file, b.item)),
            Ok(want) => match b.value {
                Some(v) if v == want => {}
                Some(v) => out.rejected.push(format!(
                    "{} {}: is {v}, but {} is {want}",
                    b.file, b.item, b.target
                )),
                None => out.rejected.push(format!(
                    "{} {}: `Model: {}` needs an initializer of literal arithmetic to compare with the model",
                    b.file, b.item, b.target
                )),
            },
        }
    }
    let Some(register) = register else {
        return Ok(out);
    };
    let have = by_value(&out.entries);
    let listed = by_value(&register.items);
    for ((file, value), n) in &have {
        let allowed = listed
            .get(&(file.clone(), value.clone()))
            .copied()
            .unwrap_or(0);
        if *n > allowed {
            let items: Vec<_> = out
                .entries
                .iter()
                .filter(|e| &e.file == file && e.values.contains_key(value))
                .map(|e| e.item.as_str())
                .collect();
            out.rejected.push(format!(
                "{file}: {} site(s) of {value} where the register admits {allowed} (in {})",
                n - allowed,
                items.join(", ")
            ));
        }
    }
    if out.rejected.is_empty() && register.items != out.entries {
        for ((file, value), n) in &listed {
            let h = have
                .get(&(file.clone(), value.clone()))
                .copied()
                .unwrap_or(0);
            if h < *n {
                out.stale
                    .push(format!("{file}: {} site(s) of {value} retired", n - h));
            }
        }
        if out.stale.is_empty() {
            out.stale
                .push("sites moved between items or facets".to_string());
        }
    }
    let total: u64 = register.items.iter().flat_map(|e| e.values.values()).sum();
    if total != register.sites {
        out.stale.push(format!(
            "sites = {} but the items list {total}",
            register.sites
        ));
    }
    Ok(out)
}

/// The rule, for messages.
pub fn rule() -> &'static str {
    RULE
}

/// A summary of the entries: totals, by facet, and the largest items.
pub fn summary(o: &Outcome) -> String {
    let mut s = String::new();
    let sites: u64 = o.entries.iter().flat_map(|e| e.values.values()).sum();
    let mut by_facet: BTreeMap<&str, u64> = BTreeMap::new();
    let mut by_file: BTreeMap<&str, u64> = BTreeMap::new();
    for e in &o.entries {
        let n: u64 = e.values.values().sum();
        *by_facet
            .entry(e.facet.as_deref().unwrap_or("(no facet named)"))
            .or_default() += n;
        *by_file.entry(e.file.as_str()).or_default() += n;
    }
    let _ = writeln!(
        s,
        "fixed figures: {sites} sites in {} items of {} files read ({} generated, judged at their source)",
        o.entries.len(),
        o.scan.files,
        o.scan.generated.len()
    );
    for (f, n) in &by_facet {
        let _ = writeln!(s, "  {n:>5}  {f}");
    }
    for (f, n) in &by_file {
        let _ = writeln!(s, "  {n:>5}  {f}");
    }
    let _ = writeln!(
        s,
        "format identities bound to the wire model: {}",
        o.scan.bindings.len()
    );
    s
}

fn read(root: &Path, rel: &str) -> Result<String, Error> {
    std::fs::read_to_string(root.join(rel)).map_err(|e| format!("{rel}: {e}"))
}

/// Read the register, if there is one.
pub fn load(root: &Path) -> Result<Option<Register>, Error> {
    match std::fs::read_to_string(root.join(REGISTER)) {
        Ok(t) => parse(&t).map(Some),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(format!("{REGISTER}: {e}")),
    }
}

/// Rewrite the register from the implementation. Refuses when the
/// implementation holds a site the register does not admit, so no count
/// ever rises; with no register it refuses unless `seed` is set.
pub fn write(root: &Path, seed: bool) -> Result<Outcome, Error> {
    let register = load(root)?;
    if register.is_none() && !seed {
        return Err(format!(
            "{REGISTER} does not exist; the first register is written with `figures seed`"
        ));
    }
    if register.is_some() && seed {
        return Err(format!(
            "{REGISTER} exists; a register is never reseeded, only lowered"
        ));
    }
    let out = check(root, register.as_ref())?;
    if !out.rejected.is_empty() {
        return Err(out.rejected.join("\n"));
    }
    std::fs::write(root.join(REGISTER), render(&out.entries))
        .map_err(|e| format!("{REGISTER}: {e}"))?;
    Ok(out)
}

