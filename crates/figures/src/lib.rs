/// The names of the `Facet` records of `Uorc.Performance`.
pub fn facets(performance: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for decl in performance.split("definition{").skip(1) {
        let decl = decl.split("\n}").next().unwrap_or(decl);
        if !decl.contains("result: Facet") {
            continue;
        }
        if let Some(name) = field(decl, "name") {
            out.insert(name.to_string());
        }
    }
    out
}

pub(crate) fn field<'a>(decl: &'a str, key: &str) -> Option<&'a str> {
    let at = decl.find(&format!("{key}: "))? + key.len() + 2;
    let rest = &decl[at..];
    let end = rest.find([',', '}', '\n']).unwrap_or(rest.len());
    Some(rest[..end].trim())
}

/// The value a wire module gives a parameterless `Nat` definition.
pub fn wire_value(root: &Path, target: &str) -> Result<u128, Error> {
    let (module, name) = target
        .rsplit_once('.')
        .ok_or_else(|| format!("`Model: {target}` names no definition"))?;
    if !WIRE_MODULES.iter().any(|p| module.starts_with(p)) {
        return Err(format!(
            "`Model: {target}`: {module} is not a wire module ({}); a value outside the wire format is a facet",
            WIRE_MODULES.join(", ")
        ));
    }
    let rel = format!("{}.lex.tex", module.replace('.', "/"));
    let text = MODEL_ROOTS
        .iter()
        .find_map(|r| std::fs::read_to_string(root.join(r).join(&rel)).ok())
        .ok_or_else(|| format!("`Model: {target}`: no module {module} under {MODEL_ROOTS:?}"))?;
    for decl in text.split("definition{").skip(1) {
        let decl = decl.split("\n}").next().unwrap_or(decl);
        if field(decl, "name") != Some(name) {
            continue;
        }
        if !decl.contains("parameters: [],") || field(decl, "result") != Some("Nat") {
            return Err(format!("`Model: {target}` is not a parameterless Nat"));
        }
        return field(decl, "body")
            .and_then(|b| b.parse().ok())
            .ok_or_else(|| format!("`Model: {target}`: its body is not a numeral"));
    }
    Err(format!("`Model: {target}`: {module} defines no {name}"))
}

// ------------------------------------------------------------- register --

/// The register entries a scan yields, in file, item order.
pub fn entries(scan: &Scan) -> Vec<Entry> {
    let mut map: BTreeMap<(String, String), Entry> = BTreeMap::new();
    for s in &scan.sites {
        let e = map
            .entry((s.file.clone(), s.item.clone()))
            .or_insert_with(|| Entry {
                file: s.file.clone(),
                item: s.item.clone(),
                facet: s.facet.clone(),
                values: BTreeMap::new(),
            });
        *e.values.entry(s.value.clone()).or_default() += 1;
    }
    map.into_values().collect()
}

/// Sites by file and value.
fn by_value(entries: &[Entry]) -> BTreeMap<(String, String), u64> {
    let mut out = BTreeMap::new();
    for e in entries {
        for (v, n) in &e.values {
            *out.entry((e.file.clone(), v.clone())).or_default() += n;
        }
    }
    out
}

fn quote(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// The register's text for these entries.
pub fn render(entries: &[Entry]) -> String {
    let sites: u64 = entries.iter().flat_map(|e| e.values.values()).sum();
    let under: u64 = entries
        .iter()
        .filter(|e| e.facet.is_some())
        .flat_map(|e| e.values.values())
        .sum();
    let mut o = String::new();
    o.push_str("# Fixed figures in uorc's implementation (written by `just figures-write`; see crates/figures).\n");
    o.push_str(
        "# Every number here is a site the Prism model does not yet derive: the distance of\n",
    );
    o.push_str("# Uorc.Performance::implementationFigures. `just figures` rejects any site not listed and\n");
    o.push_str(
        "# any listing the implementation no longer holds; the writer never raises a count.\n\n",
    );
    let _ = writeln!(o, "schema = {}", quote(SCHEMA));
    let _ = writeln!(o, "sites = {sites}");
    let _ = writeln!(o, "under_facets = {under}");
    for e in entries {
        o.push_str("\n[[item]]\n");
        let _ = writeln!(o, "file = {}", quote(&e.file));
        let _ = writeln!(o, "item = {}", quote(&e.item));
        if let Some(f) = &e.facet {
            let _ = writeln!(o, "facet = {}", quote(f));
        }
        let mut values: Vec<_> = e.values.iter().collect();
        values.sort_by(|a, b| {
            let num = |s: &str| s.parse::<u128>().ok();
            num(a.0).cmp(&num(b.0)).then(a.0.cmp(b.0))
        });
        let vs: Vec<String> = values
            .iter()
            .map(|(v, n)| format!("{} = {n}", quote(v)))
            .collect();
        let _ = writeln!(o, "values = {{ {} }}", vs.join(", "));
    }
    o
}

/// Parse a register.
pub fn parse(text: &str) -> Result<Register, Error> {
    let r: Register = toml::from_str(text).map_err(|e| format!("{REGISTER}: {e}"))?;
    if r.schema != SCHEMA {
        return Err(format!("{REGISTER}: schema {} is not {SCHEMA}", r.schema));
    }
    Ok(r)
}

