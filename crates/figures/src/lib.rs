    #[test]
    fn a_new_site_is_rejected_and_a_retired_one_makes_the_register_stale() {
        let d = tree(&[("crates/uorc/src/lib.rs", "fn f() -> u8 { 7 + 7 }")]);
        write(&d.0, true).unwrap();
        assert!(write(&d.0, true).is_err(), "a register is never reseeded");
        let reg = load(&d.0).unwrap();
        assert!(check(&d.0, reg.as_ref()).unwrap().rejected.is_empty());

        d.put("crates/uorc/src/lib.rs", "fn f() -> u8 { 7 + 7 + 9 }");
        let o = check(&d.0, reg.as_ref()).unwrap();
        assert_eq!(o.rejected.len(), 1, "{:?}", o.rejected);
        assert!(
            write(&d.0, false).is_err(),
            "the writer never raises a count"
        );

        d.put("crates/uorc/src/lib.rs", "fn g() -> u8 { 7 }");
        let o = check(&d.0, reg.as_ref()).unwrap();
        assert!(o.rejected.is_empty());
        assert_eq!(o.stale, ["crates/uorc/src/lib.rs: 1 site(s) of 7 retired"]);
        write(&d.0, false).unwrap();
        let reg = load(&d.0).unwrap().unwrap();
        assert_eq!(reg.sites, 1);
    }

