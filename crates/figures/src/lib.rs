    #[test]
    fn identities_are_admitted_and_other_literals_are_sites() {
        let s = sites("fn f(x: u32) -> u32 { (x + 1) * 0 + x >> 8 }");
        let v: Vec<_> = s
            .sites
            .iter()
            .map(|s| (s.item.as_str(), s.value.as_str()))
            .collect();
        assert_eq!(v, [("f", "8")]);
    }

