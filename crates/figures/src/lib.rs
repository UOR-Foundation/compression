//! Numbers in uorc's implementation, held against the Prism model.
//!
//! The Prism model (`Uorc.Performance`) says what a number in the codec may
//! be: a facet derived from the input and the declared host, decided by
//! outcome. A number the implementation fixes instead is an unmet
//! requirement, and this crate keeps the measure of it.
//!
//! **What is read.** The implementation is what the release ships: the
//! `src/` of every workspace crate a release obligation of the factory graph
//! builds (`-p <crate>` in the `run` of an obligation whose evidence is a
//! release artifact). Test code (`#[cfg(test)]`, `#[test]`) and files that
//! carry a `// @generated by … from <source>` first line are not read: a
//! test states an example, and a generated file is judged at its source.
//! The graph also names the rest of what ships ([`sources`]): the
//! JavaScript under the directory inputs of the obligation that builds the
//! page (a directory with a `MANIFEST.sha256` is vendored and judged at its
//! source), and the definitions of the model the shipped client is exported
//! from (the `closure:` inputs of the obligation that records the export),
//! less the modules an imported standard judges (the closure roots of an
//! obligation that reads `standards/`, such as SHA-256). The generator
//! scripts under `client/gen` are writing aids for that model, which is the
//! source, so the model is read, not the scripts.
//!
//! **Kinds of number.** Each numeric literal in the implementation is one of
//!
//! - an *identity*: `0` or `1`, the additive and multiplicative identities of
//!   the ring the operand lives in (`neg(bnot(x)) = succ(x)` makes `1` the
//!   ring's generator). They carry no choice, so they are admitted anywhere.
//! - a *format identity*: a value the wire model states. A constant whose
//!   documentation names `Model: <Module>.<definition>` is admitted when the
//!   module is one of the wire modules (`Uorc.Wire.*`, `Uorc.Codec.*`),
//!   defines that parameterless `Nat`, and the constant's value equals it.
//!   The value is what old archives depend on; the model is where it is said.
//! - a *fixed figure*: every other literal. Its site is listed in the register
//!   (`model/figures.toml`). A constant whose documentation names
//!   `Facet: <name>` attributes its sites to that facet record of
//!   `Uorc.Performance`, so the register shows which unmet facet each fixed
//!   figure belongs to. Attribution admits nothing: the facet is unmet while
//!   any site is listed under it.
//!
//! **The rule.** For every file and value, the implementation may hold at
//! most as many fixed-figure sites as the register lists. A change that
//! adds one is rejected. The register is written only by [`write`], which
//! refuses to raise any count, so the register's site count (the distance of
//! the facet `Uorc.Performance::implementationFigures`) can only fall. A
//! register that lists more than the implementation holds is stale and is
//! rejected too, so the recorded distance is always the measured one.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use syn::visit::{self, Visit};

pub mod sources;

/// The register's path from the repository root.
pub const REGISTER: &str = "model/figures.toml";
/// The factory graph the implementation's scope is read from.
pub const GRAPH: &str = "factory/graph.json";
/// The module holding the facet records.
pub const PERFORMANCE: &str = "src/Uorc/Performance.lex.tex";
/// The LexLean source roots a model module is looked up in.
pub const MODEL_ROOTS: [&str; 2] = ["src", "client/src"];
/// Module prefixes that state the wire format.
pub const WIRE_MODULES: [&str; 2] = ["Uorc.Wire.", "Uorc.Codec."];
/// The register's schema.
pub const SCHEMA: &str = "uorc/figures/1";

/// Errors are reported as text.
pub type Error = String;

/// One numeric literal in the implementation.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Site {
    /// Repository-relative path of the file.
    pub file: String,
    /// The item path the literal sits in (`ncm::Model::mix`, `FRAME`).
    pub item: String,
    /// The literal's value in base 10, without suffix or separators.
    pub value: String,
    /// The facet record its enclosing constant names, if any.
    pub facet: Option<String>,
}

/// A `Model:` binding, checked against the wire model.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Binding {
    /// Repository-relative path of the file.
    pub file: String,
    /// The constant's item path.
    pub item: String,
    /// `Module.definition`.
    pub target: String,
    /// The constant's value, when its initializer is literal arithmetic.
    pub value: Option<u128>,
}

/// Everything a scan of the implementation finds.
#[derive(Clone, Debug, Default)]
pub struct Scan {
    /// Fixed-figure sites.
    pub sites: Vec<Site>,
    /// `Model:` bindings (their sites are not in `sites`).
    pub bindings: Vec<Binding>,
    /// Generated files and the source each names.
    pub generated: Vec<(String, String)>,
    /// Files read.
    pub files: usize,
}

/// One register entry: the fixed figures of one item.
#[derive(Clone, Debug, PartialEq, Eq, serde::Deserialize)]
pub struct Entry {
    /// Repository-relative path of the file.
    pub file: String,
    /// The item path.
    pub item: String,
    /// The facet the sites are attributed to.
    #[serde(default)]
    pub facet: Option<String>,
    /// Sites by value.
    pub values: BTreeMap<String, u64>,
}

/// The register file.
#[derive(Clone, Debug, PartialEq, Eq, serde::Deserialize)]
pub struct Register {
    /// [`SCHEMA`].
    pub schema: String,
    /// Total sites (the measured distance).
    pub sites: u64,
    /// Sites attributed to a facet.
    pub under_facets: u64,
    /// Entries in file, item order.
    #[serde(default, rename = "item")]
    pub items: Vec<Entry>,
}

// ---------------------------------------------------------------- scope --

/// The workspace crates a release obligation builds, read from the factory
/// graph: every `-p <name>` in the `run` of an obligation whose `evidence`
/// is a release artifact.
pub fn shipped_packages(graph: &str) -> Result<BTreeSet<String>, Error> {
    let value: serde_json::Value =
        serde_json::from_str(graph).map_err(|e| format!("{GRAPH}: {e}"))?;
    let obligations = value["obligations"]
        .as_array()
        .ok_or_else(|| format!("{GRAPH}: no obligations"))?;
    let mut out = BTreeSet::new();
    for o in obligations {
        if o["evidence"].as_str().is_none() {
            continue;
        }
        let run = o["run"].as_str().unwrap_or_default();
        let mut words = run.split_whitespace();
        while let Some(w) = words.next() {
            if w == "-p" {
                if let Some(p) = words.next() {
                    out.insert(p.to_string());
                }
            }
        }
    }
    if out.is_empty() {
        return Err(format!("{GRAPH}: no release obligation builds a package"));
    }
    Ok(out)
}

/// The `src/` directory of each shipped package, found by the `name` of the
/// workspace crates' manifests under `crates/`.
pub fn scope(root: &Path) -> Result<Vec<String>, Error> {
    let graph = read(root, GRAPH)?;
    let wanted = shipped_packages(&graph)?;
    let mut found = BTreeMap::new();
    let crates = root.join("crates");
    let dirs = std::fs::read_dir(&crates).map_err(|e| format!("{}: {e}", crates.display()))?;
    for dir in dirs.flatten() {
        let manifest = dir.path().join("Cargo.toml");
        let Ok(text) = std::fs::read_to_string(&manifest) else {
            continue;
        };
        let parsed: toml::Value =
            toml::from_str(&text).map_err(|e| format!("{}: {e}", manifest.display()))?;
        if let Some(name) = parsed
            .get("package")
            .and_then(|p| p.get("name"))
            .and_then(|n| n.as_str())
        {
            if wanted.contains(name) {
                let rel = format!("crates/{}/src", dir.file_name().to_string_lossy());
                found.insert(name.to_string(), rel);
            }
        }
    }
    let missing: Vec<_> = wanted.iter().filter(|p| !found.contains_key(*p)).collect();
    if !missing.is_empty() {
        return Err(format!(
            "the release builds {missing:?}, which is not a crate under crates/"
        ));
    }
    Ok(found.into_values().collect())
}

// ----------------------------------------------------------------- scan --

/// Scan every `.rs` file under the scope directories.
pub fn scan(root: &Path, dirs: &[String]) -> Result<Scan, Error> {
    let mut files = Vec::new();
    for d in dirs {
        collect(&root.join(d), &mut files)?;
    }
    files.sort();
    let mut out = Scan::default();
    for path in files {
        let rel = path
            .strip_prefix(root)
            .map_err(|e| e.to_string())?
            .to_string_lossy()
            .replace('\\', "/");
        let text = std::fs::read_to_string(&path).map_err(|e| format!("{rel}: {e}"))?;
        scan_source(&rel, &text, &mut out)?;
    }
    Ok(out)
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), Error> {
    let entries = std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() {
            collect(&p, out)?;
        } else if p.extension().is_some_and(|x| x == "rs") {
            out.push(p);
        }
    }
    Ok(())
}

/// Scan one file's source into `out`.
pub fn scan_source(file: &str, text: &str, out: &mut Scan) -> Result<(), Error> {
    out.files += 1;
    if let Some(first) = text.lines().next() {
        if let Some(rest) = first.trim().strip_prefix("// @generated by") {
            let source = rest.split(" from ").nth(1).map(|s| {
                s.split(|c: char| c.is_whitespace() || c == ';' || c == ',')
                    .next()
                    .unwrap_or_default()
                    .to_string()
            });
            return match source {
                Some(s) if !s.is_empty() => {
                    out.generated.push((file.to_string(), s));
                    Ok(())
                }
                _ => Err(format!("{file}: a generated file names its source (`// @generated by <tool> from <source>`)")),
            };
        }
    }
    let ast = syn::parse_file(text).map_err(|e| format!("{file}: {e}"))?;
    let mut v = Visitor {
        file,
        path: Vec::new(),
        facet: None,
        admitted: false,
        out,
    };
    v.visit_file(&ast);
    Ok(())
}

struct Visitor<'a> {
    file: &'a str,
    path: Vec<String>,
    facet: Option<String>,
    admitted: bool,
    out: &'a mut Scan,
}

/// Whether the attributes make the item test code.
fn is_test(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|a| {
        if a.path().is_ident("test") {
            return true;
        }
        if !a.path().is_ident("cfg") {
            return false;
        }
        let syn::Meta::List(list) = &a.meta else {
            return false;
        };
        let mut idents = BTreeSet::new();
        idents_in(list.tokens.clone(), &mut idents);
        idents.contains("test") && !idents.contains("not")
    })
}

fn idents_in(tokens: proc_macro2::TokenStream, out: &mut BTreeSet<String>) {
    for t in tokens {
        match t {
            proc_macro2::TokenTree::Ident(i) => {
                out.insert(i.to_string());
            }
            proc_macro2::TokenTree::Group(g) => idents_in(g.stream(), out),
            _ => {}
        }
    }
}

/// The documentation lines of an item.
fn doc_lines(attrs: &[syn::Attribute]) -> Vec<String> {
    let mut out = Vec::new();
    for a in attrs {
        if !a.path().is_ident("doc") {
            continue;
        }
        if let syn::Meta::NameValue(nv) = &a.meta {
            if let syn::Expr::Lit(syn::ExprLit {
                lit: syn::Lit::Str(s),
                ..
            }) = &nv.value
            {
                out.push(s.value().trim().to_string());
            }
        }
    }
    out
}

fn tag(attrs: &[syn::Attribute], key: &str) -> Option<String> {
    doc_lines(attrs).iter().find_map(|l| {
        l.strip_prefix(key)
            .map(|v| v.trim().trim_end_matches('.').trim_matches('`').to_string())
    })
}

/// The value of literal integer arithmetic, if that is all the expression is.
pub fn evaluate(e: &syn::Expr) -> Option<u128> {
    use syn::{BinOp, Expr, Lit};
    match e {
        Expr::Lit(l) => match &l.lit {
            Lit::Int(i) => i.base10_digits().parse().ok(),
            _ => None,
        },
        Expr::Paren(p) => evaluate(&p.expr),
        Expr::Group(g) => evaluate(&g.expr),
        Expr::Cast(c) => evaluate(&c.expr),
        Expr::Binary(b) => {
            let (l, r) = (evaluate(&b.left)?, evaluate(&b.right)?);
            match b.op {
                BinOp::Add(_) => l.checked_add(r),
                BinOp::Sub(_) => l.checked_sub(r),
                BinOp::Mul(_) => l.checked_mul(r),
                BinOp::Div(_) => l.checked_div(r),
                BinOp::Shl(_) => u32::try_from(r).ok().and_then(|r| l.checked_shl(r)),
                BinOp::Shr(_) => u32::try_from(r).ok().and_then(|r| l.checked_shr(r)),
                BinOp::BitOr(_) => Some(l | r),
                BinOp::BitAnd(_) => Some(l & r),
                BinOp::BitXor(_) => Some(l ^ r),
                _ => None,
            }
        }
        _ => None,
    }
}

impl Visitor<'_> {
    fn item(&self) -> String {
        if self.path.is_empty() {
            "(file)".to_string()
        } else {
            self.path.join("::")
        }
    }

    fn literal(&mut self, value: String) {
        if self.admitted || value == "0" || value == "1" {
            return;
        }
        self.out.sites.push(Site {
            file: self.file.to_string(),
            item: self.item(),
            value,
            facet: self.facet.clone(),
        });
    }

    fn tokens(&mut self, tokens: proc_macro2::TokenStream) {
        for t in tokens {
            match t {
                proc_macro2::TokenTree::Literal(l) => match syn::Lit::new(l) {
                    syn::Lit::Int(i) => self.literal(i.base10_digits().to_string()),
                    syn::Lit::Float(f) => self.literal(f.base10_digits().to_string()),
                    _ => {}
                },
                proc_macro2::TokenTree::Group(g) => self.tokens(g.stream()),
                _ => {}
            }
        }
    }

    fn named<F: FnOnce(&mut Self)>(&mut self, name: String, f: F) {
        self.path.push(name);
        f(self);
        self.path.pop();
    }

    /// A constant or static: its tags set the facet or the admission of
    /// every literal of its initializer.
    fn constant<F: FnOnce(&mut Self)>(
        &mut self,
        attrs: &[syn::Attribute],
        name: String,
        init: Option<&syn::Expr>,
        f: F,
    ) {
        let facet = tag(attrs, "Facet:");
        let model = tag(attrs, "Model:");
        self.path.push(name);
        let (saved_facet, saved_admitted) = (self.facet.clone(), self.admitted);
        if let Some(target) = model {
            self.out.bindings.push(Binding {
                file: self.file.to_string(),
                item: self.item(),
                target,
                value: init.and_then(evaluate),
            });
            self.admitted = true;
        }
        if facet.is_some() {
            self.facet = facet;
        }
        f(self);
        self.facet = saved_facet;
        self.admitted = saved_admitted;
        self.path.pop();
    }
}

fn type_name(t: &syn::Type) -> Option<String> {
    match t {
        syn::Type::Path(p) => p.path.segments.last().map(|s| s.ident.to_string()),
        _ => None,
    }
}

impl<'ast> Visit<'ast> for Visitor<'_> {
    fn visit_lit_int(&mut self, i: &'ast syn::LitInt) {
        self.literal(i.base10_digits().to_string());
    }

    fn visit_lit_float(&mut self, f: &'ast syn::LitFloat) {
        self.literal(f.base10_digits().to_string());
    }

    fn visit_macro(&mut self, m: &'ast syn::Macro) {
        self.tokens(m.tokens.clone());
    }

    fn visit_attribute(&mut self, a: &'ast syn::Attribute) {
        match &a.meta {
            syn::Meta::List(list)
                if !a.path().is_ident("cfg") && !a.path().is_ident("cfg_attr") =>
            {
                self.tokens(list.tokens.clone())
            }
            _ => visit::visit_attribute(self, a),
        }
    }

    fn visit_item_mod(&mut self, i: &'ast syn::ItemMod) {
        if is_test(&i.attrs) {
            return;
        }
        self.named(i.ident.to_string(), |v| visit::visit_item_mod(v, i));
    }

    fn visit_item_fn(&mut self, i: &'ast syn::ItemFn) {
        if is_test(&i.attrs) {
            return;
        }
        self.named(i.sig.ident.to_string(), |v| visit::visit_item_fn(v, i));
    }

    fn visit_item_impl(&mut self, i: &'ast syn::ItemImpl) {
        if is_test(&i.attrs) {
            return;
        }
        let ty = type_name(&i.self_ty).unwrap_or_else(|| "impl".to_string());
        let name = match &i.trait_ {
            Some((path, _)) => match path.segments.last() {
                Some(s) => format!("<{ty} as {}>", s.ident),
                None => ty,
            },
            None => ty,
        };
        self.named(name, |v| visit::visit_item_impl(v, i));
    }

    fn visit_impl_item_fn(&mut self, i: &'ast syn::ImplItemFn) {
        if is_test(&i.attrs) {
            return;
        }
        self.named(i.sig.ident.to_string(), |v| visit::visit_impl_item_fn(v, i));
    }

    fn visit_trait_item_fn(&mut self, i: &'ast syn::TraitItemFn) {
        self.named(i.sig.ident.to_string(), |v| {
            visit::visit_trait_item_fn(v, i)
        });
    }

    fn visit_item_trait(&mut self, i: &'ast syn::ItemTrait) {
        if is_test(&i.attrs) {
            return;
        }
        self.named(i.ident.to_string(), |v| visit::visit_item_trait(v, i));
    }

    fn visit_item_struct(&mut self, i: &'ast syn::ItemStruct) {
        if is_test(&i.attrs) {
            return;
        }
        self.named(i.ident.to_string(), |v| visit::visit_item_struct(v, i));
    }

    fn visit_item_enum(&mut self, i: &'ast syn::ItemEnum) {
        if is_test(&i.attrs) {
            return;
        }
        self.named(i.ident.to_string(), |v| visit::visit_item_enum(v, i));
    }

    fn visit_item_macro(&mut self, i: &'ast syn::ItemMacro) {
        if is_test(&i.attrs) {
            return;
        }
        let name = match &i.ident {
            Some(id) => id.to_string(),
            None => i
                .mac
                .path
                .segments
                .last()
                .map(|s| format!("{}!", s.ident))
                .unwrap_or_default(),
        };
        self.named(name, |v| visit::visit_item_macro(v, i));
    }

    fn visit_item_const(&mut self, i: &'ast syn::ItemConst) {
        if is_test(&i.attrs) {
            return;
        }
        self.constant(&i.attrs, i.ident.to_string(), Some(&i.expr), |v| {
            visit::visit_item_const(v, i)
        });
    }

    fn visit_item_static(&mut self, i: &'ast syn::ItemStatic) {
        if is_test(&i.attrs) {
            return;
        }
        self.constant(&i.attrs, i.ident.to_string(), Some(&i.expr), |v| {
            visit::visit_item_static(v, i)
        });
    }

    fn visit_impl_item_const(&mut self, i: &'ast syn::ImplItemConst) {
        if is_test(&i.attrs) {
            return;
        }
        self.constant(&i.attrs, i.ident.to_string(), Some(&i.expr), |v| {
            visit::visit_impl_item_const(v, i)
        });
    }

    fn visit_trait_item_const(&mut self, i: &'ast syn::TraitItemConst) {
        let init = i.default.as_ref().map(|(_, e)| e);
        self.constant(&i.attrs, i.ident.to_string(), init, |v| {
            visit::visit_trait_item_const(v, i)
        });
    }
}

