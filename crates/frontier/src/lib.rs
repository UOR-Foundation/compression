//! uorc's claim register and its decider.
//!
//! A closed claim says "codec point X codes corpus κ in exactly N bytes and S
//! steps". Archive sizes and model step counts are deterministic, so such a
//! claim is not a timing: it is decided by running the shipped codec over the
//! corpus, and it is true or false. The register (`frontier.toml` at the
//! repository root) holds every corpus, codec point and claim by κ:
//!
//! - a **corpus** is an ordered list of members (name, SHA-256, length); its
//!   κ is [`corpus_kappa`] over that list, so the corpus is the same object
//!   wherever its bytes come from (a download, a directory, git objects);
//! - a **codec point** is where the codec sits in its modelled space: the
//!   export identity of the model the native code is byte-identical to, the
//!   strategy plan (the portfolio under a weight table, or one fixed
//!   strategy), the consolidated model state κ and the lane count; its κ is
//!   [`CodecPoint::kappa`];
//! - a **claim** is one of the forms of `Uorc.Performance`: closed (point,
//!   corpus, bytes, steps), bound (point, corpus, at most B bytes, B from a
//!   pinned comparator), dominance (candidate, incumbent, family: bytes and
//!   steps no larger, one strictly smaller) and exclusion (a refuted point,
//!   never rerun). Its κ is the κ of the question ([`claim_kappa`]), not of
//!   the answer, so a question known by κ is never asked twice.
//!
//! Steps are decode steps, read from each frame's header by
//! [`uorc::performance::frame_steps`]: one model input evaluated for one coded bit.
//!
//! Who decided a claim is part of the record. A result a workstation wrote is
//! `local`; the factory obligation `frontier` re-decides every claim that is
//! not yet decided by the factory and then never again.

