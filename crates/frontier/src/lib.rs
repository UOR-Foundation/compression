/// The register's schema name.
pub const SCHEMA: &str = "uorc/frontier/1";

/// Names of the portfolio's frame families, in [`portfolio::family`] order.
pub const FAMILIES: [&str; portfolio::FAMILIES] = portfolio::FAMILY_NAMES;

pub use portfolio::{ENTRY, X86_BIT};

/// The [`ENTRY`] bytes of a strategy.
pub fn entry(s: Strategy) -> [u8; ENTRY] {
    s.entry()
}

/// The strategy an entry names, when the coder can apply it: a valid
/// profile word, no other word bits, and no state.
pub fn strategy_of(e: &[u8]) -> Option<Strategy> {
    if e.len() != ENTRY {
        return None;
    }
    portfolio::Table {
        strategies: e,
        weights: &[],
    }
    .strategy(0)
}

/// The strategy coordinate of a codec point: a portfolio table (strategy
/// entries and one weight per family and entry, the byte form the engine
/// consolidates), or one fixed strategy (coded exactly as the shipped
/// encoder codes that strategy, learned context mask included).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Plan {
    /// A portfolio: [`ENTRY`] bytes per strategy, and `FAMILIES * count`
    /// weights, row by family.
    Portfolio {
        /// The strategy entries.
        strategies: Vec<u8>,
        /// The weights, row by family.
        weights: Vec<u8>,
    },
    /// One strategy for every frame.
    Fixed(Strategy),
}

impl Plan {
    /// The shipped portfolio ([`portfolio::SHIPPED`], generated by the
    /// engine into `weights.rs`).
    pub fn shipped() -> Plan {
        Plan::Portfolio {
            strategies: portfolio::SHIPPED.strategies.to_vec(),
            weights: portfolio::SHIPPED.weights.to_vec(),
        }
    }

    /// The strategies this plan codes for `frame`, in order: a portfolio's
    /// [`portfolio::Table::plan`] (the first [`portfolio::BUDGET`] entries
    /// by the frame family's weights, highest first, ties in table order),
    /// or the fixed strategy.
    pub fn strategies(&self, frame: &[u8]) -> Vec<Option<Strategy>> {
        match self {
            Plan::Fixed(s) => vec![Some(*s)],
            Plan::Portfolio {
                strategies,
                weights,
            } => portfolio::Table {
                strategies,
                weights,
            }
            .plan(frame),
        }
    }

    /// The stream of `input` under this plan: framed exactly as the shipped
    /// encoder frames it (repeats, windows), each coded frame coded by
    /// [`uorc::compress_with_strategies`], frames on up to `threads` cores.
    pub fn compress(&self, input: &[u8], threads: usize) -> Vec<u8> {
        let mut encoder = uorc::FrameEncoder::new();
        let mut planned = encoder.plan(input);
        planned.extend(encoder.plan_end());
        let code = |p: &uorc::Planned| match p {
            uorc::Planned::Done { archive, .. } => archive.clone(),
            uorc::Planned::Code {
                bytes,
                pieces,
                window,
            } => {
                let window: Vec<&[u8]> = window.iter().map(Vec::as_slice).collect();
                uorc::compress_with_strategies(bytes, pieces, &window, &self.strategies(bytes))
            }
        };
        let mut out = Vec::new();
        for chunk in planned.chunks(threads.max(1)) {
            let archives: Vec<Vec<u8>> = std::thread::scope(|s| {
                let handles: Vec<_> = chunk.iter().map(|p| s.spawn(move || code(p))).collect();
                handles
                    .into_iter()
                    .map(|h| h.join().expect("frame thread"))
                    .collect()
            });
            for a in archives {
                out.extend_from_slice(&a);
            }
        }
        out
    }
}

/// A failure of the register or the decider.
#[derive(Debug)]
pub enum Error {
    /// Reading or writing a file failed.
    Io(String, io::Error),
    /// The register is not valid TOML of this schema.
    Parse(String),
    /// The register contradicts itself (a stored κ that does not recompute).
    Inconsistent(String),
    /// A corpus member's bytes are not the ones its κ names.
    Member(String),
    /// The codec failed on a member: it did not compress, did not round-trip,
    /// or wrote a frame with no step value.
    Codec(String),
    /// A name the register does not hold.
    Unknown(String),
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Error::Io(path, e) => write!(f, "{path}: {e}"),
            Error::Parse(m) => write!(f, "frontier.toml: {m}"),
            Error::Inconsistent(m) => write!(f, "frontier.toml is inconsistent: {m}"),
            Error::Member(m) => write!(f, "corpus member: {m}"),
            Error::Codec(m) => write!(f, "codec: {m}"),
            Error::Unknown(m) => write!(f, "unknown: {m}"),
        }
    }
}

impl std::error::Error for Error {}

/// SHA-256 as lowercase hex.
pub fn sha256_hex(bytes: &[u8]) -> String {
    hex(&Sha256::digest(bytes))
}

/// One member of a corpus.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct Member {
    /// The member's name (a file name, or a path in a git tree).
    pub name: String,
    /// SHA-256 of its bytes, lowercase hex.
    pub sha256: String,
    /// Its length in bytes.
    pub bytes: u64,
}

impl Member {
    /// The member record of `bytes` under `name`.
    pub fn of(name: &str, bytes: &[u8]) -> Member {
        Member {
            name: name.to_owned(),
            sha256: sha256_hex(bytes),
            bytes: bytes.len() as u64,
        }
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn unhex(s: &str) -> Option<Vec<u8>> {
    s.len()
        .is_multiple_of(2)
        .then(|| {
            (0..s.len() / 2)
                .map(|k| u8::from_str_radix(s.get(2 * k..2 * k + 2)?, 16).ok())
                .collect()
        })
        .flatten()
}

fn unhex32(s: &str) -> Option<[u8; 32]> {
    if s.len() != 64 {
        return None;
    }
    let mut out = [0; 32];
    for (k, o) in out.iter_mut().enumerate() {
        *o = u8::from_str_radix(s.get(2 * k..2 * k + 2)?, 16).ok()?;
    }
    Some(out)
}

/// The κ of a corpus, as `Uorc.Performance` defines it
/// ([`uorc::performance::corpus_kappa`]: SHA-256 over `uorc/corpus/1` and
/// each member's name length, name, SHA-256 and length), as hex. A member
/// whose SHA-256 is not 64 hex digits names no corpus.
pub fn corpus_kappa(members: &[Member]) -> String {
    let digests: Vec<[u8; 32]> = members
        .iter()
        .map(|m| unhex32(&m.sha256).unwrap_or([0xff; 32]))
        .collect();
    hex(&uorc::performance::corpus_kappa(
        members
            .iter()
            .zip(&digests)
            .map(|(m, d)| (m.name.as_str(), *d, m.bytes)),
    ))
}

/// A κ-named corpus.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct Corpus {
    /// A short name, used on the command line and in reports.
    pub name: String,
    /// [`corpus_kappa`] of `members`.
    pub kappa: String,
    /// Where the bytes come from: a URL, or `git:<rev>` (each member is the
    /// blob at that path in that revision, so the corpus needs no network).
    pub source: String,
    /// A public corpus: its bound claims are UC-PERF-01's target.
    #[serde(default)]
    pub public: bool,
    /// The members, in order.
    pub members: Vec<Member>,
}

impl Corpus {
    /// A corpus of `members` from `source`, its κ computed.
    pub fn new(name: &str, source: &str, public: bool, members: Vec<Member>) -> Corpus {
        Corpus {
            name: name.to_owned(),
            kappa: corpus_kappa(&members),
            source: source.to_owned(),
            public,
            members,
        }
    }

    /// Total input bytes.
    pub fn bytes(&self) -> u64 {
        self.members.iter().map(|m| m.bytes).sum()
    }

    /// The members' bytes, read from `dir` (one file per member name) or,
    /// for a `git:<rev>` source with no `dir`, from the git objects of
    /// `repo`. Every member is checked against its length and SHA-256.
    pub fn materialize(&self, dir: Option<&Path>, repo: &Path) -> Result<Vec<Vec<u8>>, Error> {
        self.members
            .iter()
            .map(|m| {
                let bytes = match (dir, self.source.strip_prefix("git:")) {
                    (Some(dir), _) => {
                        let path = dir.join(&m.name);
                        std::fs::read(&path)
                            .map_err(|e| Error::Io(path.display().to_string(), e))?
                    }
                    (None, Some(rev)) => git_blob(repo, rev, &m.name)?,
                    (None, None) => {
                        return Err(Error::Member(format!(
                            "{}: corpus {} needs a directory (source {})",
                            m.name, self.name, self.source
                        )))
                    }
                };
                if bytes.len() as u64 != m.bytes || sha256_hex(&bytes) != m.sha256 {
                    return Err(Error::Member(format!(
                        "{} in corpus {} is not the member its κ names",
                        m.name, self.name
                    )));
                }
                Ok(bytes)
            })
            .collect()
    }
}

fn git_blob(repo: &Path, rev: &str, path: &str) -> Result<Vec<u8>, Error> {
    let out = std::process::Command::new("git")
        .arg("-C")
        .arg(repo)
        .args(["cat-file", "blob", &format!("{rev}:{path}")])
        .output()
        .map_err(|e| Error::Io("git".to_owned(), e))?;
    if !out.status.success() {
        return Err(Error::Member(format!(
            "git {rev}:{path}: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        )));
    }
    Ok(out.stdout)
}

/// A point in the codec's modelled space.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CodecPoint {
    /// The export identity of the model the native codec is byte-identical
    /// to (`generated/rust/factory.identity`).
    pub export: String,
    /// The strategy coordinate: the portfolio under a weight table, or one
    /// fixed strategy.
    pub plan: Plan,
    /// The κ of the consolidated model state the coder starts from; `None`
    /// for a fresh model.
    pub state: Option<String>,
    /// Independent lanes per frame (1: one coder per frame).
    pub lanes: u32,
}

impl CodecPoint {
    /// The shipped client's point for export identity `export`: the
    /// portfolio under the learned weights, a fresh model, one lane.
    pub fn shipped(export: &str) -> CodecPoint {
        CodecPoint {
            export: export.to_owned(),
            plan: Plan::shipped(),
            state: None,
            lanes: 1,
        }
    }

    /// The plan in a few words.
    pub fn plan_text(&self) -> String {
        match &self.plan {
            Plan::Portfolio { strategies, .. } => {
                format!("portfolio of {}", strategies.len() / ENTRY)
            }
            Plan::Fixed(s) => format!("fixed x86={} profile=0x{:05x}", u8::from(s.x86), s.profile),
        }
    }

    /// The point's κ: SHA-256 over `uorc/encoder-point/1`, the export
    /// identity (32 bytes), the plan (`0`, then the SHA-256 of the strategy
    /// entries and of the weights; or `1` and the strategy's entry), the
    /// state κ (32 bytes, zeros for none) and the lane count (u32 LE). It names the encoder's
    /// coordinates; each frame the encoder writes has its own frame point,
    /// [`uorc::performance::CodecPoint`].
    pub fn kappa(&self) -> String {
        let mut h = Sha256::new();
        h.update(b"uorc/encoder-point/1");
        h.update(
            unhex32(&self.export).unwrap_or_else(|| Sha256::digest(self.export.as_bytes()).into()),
        );
        match &self.plan {
            Plan::Portfolio {
                strategies,
                weights,
            } => {
                h.update([0u8]);
                h.update(Sha256::digest(strategies));
                h.update(Sha256::digest(weights));
            }
            Plan::Fixed(s) => {
                h.update([1u8]);
                h.update(entry(*s));
            }
        }
        h.update(self.state.as_deref().and_then(unhex32).unwrap_or([0; 32]));
        h.update(self.lanes.to_le_bytes());
        hex(&h.finalize())
    }

    /// The register record of this point.
    pub fn record(&self, label: Option<&str>) -> Point {
        let (strategies, weights, x86, profile) = match &self.plan {
            Plan::Portfolio {
                strategies,
                weights,
            } => (Some(hex(strategies)), Some(hex(weights)), None, None),
            Plan::Fixed(s) => (
                None,
                None,
                Some(s.x86),
                Some(format!("0x{:05x}", s.profile)),
            ),
        };
        Point {
            kappa: self.kappa(),
            label: label.map(str::to_owned),
            export: self.export.clone(),
            plan: match self.plan {
                Plan::Portfolio { .. } => "portfolio",
                Plan::Fixed(_) => "fixed",
            }
            .to_owned(),
            strategies,
            weights,
            x86,
            profile,
            state: self.state.clone(),
            lanes: self.lanes,
        }
    }
}

/// A codec point as the register stores it.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct Point {
    /// [`CodecPoint::kappa`].
    pub kappa: String,
    /// A reader's name for the point (`v0.5.0`, `fixed FULL`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub label: Option<String>,
    /// The export identity.
    pub export: String,
    /// `portfolio` or `fixed`.
    pub plan: String,
    /// A portfolio's strategy entries, hex.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub strategies: Option<String>,
    /// A portfolio's weights, hex, row by family.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub weights: Option<String>,
    /// A fixed strategy's transform.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub x86: Option<bool>,
    /// A fixed strategy's ncm profile word.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub profile: Option<String>,
    /// The consolidated model state κ.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub state: Option<String>,
    /// Lanes per frame.
    pub lanes: u32,
}

impl Point {
    /// The codec point this record names.
    pub fn point(&self) -> Result<CodecPoint, Error> {
        let bad = || Error::Inconsistent(format!("point {} has no valid plan", self.kappa));
        let plan = match self.plan.as_str() {
            "portfolio" => Plan::Portfolio {
                strategies: self.strategies.as_deref().and_then(unhex).ok_or_else(bad)?,
                weights: self.weights.as_deref().and_then(unhex).ok_or_else(bad)?,
            },
            "fixed" => {
                let profile = self
                    .profile
                    .as_deref()
                    .and_then(|p| p.strip_prefix("0x"))
                    .and_then(|p| u32::from_str_radix(p, 16).ok())
                    .filter(|&p| uorc::ncm::valid_profile(p))
                    .ok_or_else(bad)?;
                Plan::Fixed(Strategy {
                    x86: self.x86.ok_or_else(bad)?,
                    profile,
                    state: 0,
                })
            }
            _ => return Err(bad()),
        };
        Ok(CodecPoint {
            export: self.export.clone(),
            plan,
            state: self.state.clone(),
            lanes: self.lanes,
        })
    }
}

/// A claim's form (`Uorc.Performance`).
#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum Form {
    /// Codec point X codes corpus κ in exactly N bytes and S steps.
    Closed,
    /// Codec point X codes corpus κ in at most B bytes (B pinned from a
    /// comparator).
    Bound,
    /// Candidate dominates incumbent on a family of corpus κ: bytes and
    /// steps no larger, one strictly smaller.
    Dominance,
    /// A refuted point, recorded so that it is never rerun.
    Exclusion,
    /// A point excluded on every corpus by a named kernel theorem (a
    /// template and its parameter): recorded with no corpus, so its κ
    /// blocks the point everywhere without a run.
    Universal,
}

/// A claim's status.
#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum Status {
    /// Minted, not decided yet.
    Minted,
    /// Decided true.
    Proved,
    /// Decided false.
    Refuted,
}

impl Status {
    /// Lowercase name.
    pub fn name(self) -> &'static str {
        match self {
            Status::Minted => "minted",
            Status::Proved => "proved",
            Status::Refuted => "refuted",
        }
    }
}

/// One member's exact result under a codec point.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct MemberResult {
    /// The member's name.
    pub name: String,
    /// The portfolio family of its first frame ([`FAMILIES`]).
    pub family: String,
    /// Archive bytes.
    pub bytes: u64,
    /// Decode steps.
    pub steps: u64,
}

/// The answer to a closed claim.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Closed {
    /// Total archive bytes over the corpus.
    pub bytes: u64,
    /// Total decode steps over the corpus.
    pub steps: u64,
    /// Per member, in corpus order.
    pub members: Vec<MemberResult>,
}

impl Closed {
    /// Sums over the members of `family` (`None`: every member).
    pub fn family(&self, family: Option<&str>) -> (u64, u64) {
        self.members
            .iter()
            .filter(|m| family.is_none_or(|f| m.family == f))
            .fold((0, 0), |(b, s), m| (b + m.bytes, s + m.steps))
    }
}

/// Whether `candidate` dominates `incumbent` on `family` (`None`: the whole
/// corpus): no more bytes and no more steps, and strictly fewer of one.
pub fn dominates(candidate: &Closed, incumbent: &Closed, family: Option<&str>) -> bool {
    let (cb, cs) = candidate.family(family);
    let (ib, is) = incumbent.family(family);
    cb <= ib && cs <= is && (cb < ib || cs < is)
}

/// One claim of the register.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct Claim {
    /// The claim's κ: [`claim_kappa`] of its question.
    pub id: String,
    /// The form.
    pub form: Form,
    /// The status.
    pub status: Status,
    /// Who decided it: `local` (a workstation run), or
    /// `factory:<obligation identity>` (the factory obligation `frontier`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub receipt: Option<String>,
    /// The corpus κ; empty for a universal claim (every corpus).
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub corpus: String,
    /// The codec point κ (closed, bound, exclusion).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub codec: Option<String>,
    /// The candidate point κ (dominance).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub candidate: Option<String>,
    /// The incumbent point κ (dominance).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub incumbent: Option<String>,
    /// The family (dominance); absent for the whole corpus.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub family: Option<String>,
    /// The kernel theorem that decides a universal claim (its template).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub theorem: Option<String>,
    /// The theorem template's parameter.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parameter: Option<String>,
    /// The comparator a bound comes from (`xz -9e`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub against: Option<String>,
    /// The bound in bytes (bound).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub bound: Option<u64>,
    /// Exact archive bytes (closed): stated, then decided.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub bytes: Option<u64>,
    /// Exact decode steps (closed): stated, then decided.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub steps: Option<u64>,
    /// What the deciding run observed when it refuted a stated closed claim.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub observed_bytes: Option<u64>,
    /// What the deciding run observed when it refuted a stated closed claim.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub observed_steps: Option<u64>,
    /// Per member results (closed).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub members: Vec<MemberResult>,
}

impl Claim {
    fn question(form: Form, corpus: &str) -> Claim {
        Claim {
            id: String::new(),
            form,
            status: Status::Minted,
            receipt: None,
            corpus: corpus.to_owned(),
            codec: None,
            candidate: None,
            incumbent: None,
            family: None,
            theorem: None,
            parameter: None,
            against: None,
            bound: None,
            bytes: None,
            steps: None,
            observed_bytes: None,
            observed_steps: None,
            members: Vec::new(),
        }
    }

    /// The closed claim's answer, when it has one.
    pub fn closed(&self) -> Option<Closed> {
        Some(Closed {
            bytes: self.bytes?,
            steps: self.steps?,
            members: self.members.clone(),
        })
    }

    /// Whether the factory decided it (and so it is never decided again).
    pub fn final_(&self) -> bool {
        self.status != Status::Minted
            && self
                .receipt
                .as_deref()
                .is_some_and(|b| b.starts_with("factory:"))
    }
}

/// The κ of a claim's question: SHA-256 of `uorc/claim/1`, the form, and the
/// question's fields (codec or candidate and incumbent, corpus, family, the
/// theorem and its parameter, the comparator and bound), one `key value` line
/// each; an absent field (a universal claim's corpus) has no line.
pub fn claim_kappa(claim: &Claim) -> String {
    let mut text = format!("uorc/claim/1\nform {:?}\n", claim.form).to_lowercase();
    let mut line = |k: &str, v: Option<String>| {
        if let Some(v) = v {
            text.push_str(&format!("{k} {v}\n"));
        }
    };
    line("codec", claim.codec.clone());
    line("candidate", claim.candidate.clone());
    line("incumbent", claim.incumbent.clone());
    line(
        "corpus",
        (!claim.corpus.is_empty()).then(|| claim.corpus.clone()),
    );
    line("family", claim.family.clone());
    line("theorem", claim.theorem.clone());
    line("parameter", claim.parameter.clone());
    line("against", claim.against.clone());
    line("bound", claim.bound.map(|b| b.to_string()));
    sha256_hex(text.as_bytes())
}

/// A comparator's pinned archive size on a corpus: a fact measured once by
/// running that tool version, kept as a validation authority (it never
/// enters uorc's coding).
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct Comparator {
    /// The corpus κ.
    pub corpus: String,
    /// Tool and settings (`xz -9e`).
    pub tool: String,
    /// The tool's version line.
    pub version: String,
    /// Total archive bytes over the corpus.
    pub bytes: u64,
    /// Where the measurement was published.
    pub source: String,
}

/// The register, `frontier.toml`.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct Register {
    /// [`SCHEMA`].
    pub schema: String,
    /// κ-named corpora.
    #[serde(default)]
    pub corpus: Vec<Corpus>,
    /// Pinned comparator sizes.
    #[serde(default)]
    pub comparator: Vec<Comparator>,
    /// Codec points.
    #[serde(default)]
    pub point: Vec<Point>,
    /// Claims, in the order they were minted.
    #[serde(default)]
    pub claim: Vec<Claim>,
}

impl Default for Register {
    fn default() -> Register {
        Register {
            schema: SCHEMA.to_owned(),
            corpus: Vec::new(),
            comparator: Vec::new(),
            point: Vec::new(),
            claim: Vec::new(),
        }
    }
}

const HEADER: &str =
    "# uorc claim register (uorc/frontier/1). Written by `frontier`; see crates/frontier.\n\
# Every κ here recomputes from the fields beside it (`frontier check`).\n\n";

impl Register {
    /// Parse a register from TOML text and check it ([`Register::check`]).
    pub fn parse(text: &str) -> Result<Register, Error> {
        let register: Register = toml::from_str(text).map_err(|e| Error::Parse(e.to_string()))?;
        register.check()?;
        Ok(register)
    }

    /// Read the register at `path`.
    pub fn load(path: &Path) -> Result<Register, Error> {
        let text =
            std::fs::read_to_string(path).map_err(|e| Error::Io(path.display().to_string(), e))?;
        Register::parse(&text)
    }

    /// The register as TOML text, exactly as [`Register::save`] writes it.
    pub fn to_text(&self) -> Result<String, Error> {
        let body = toml::to_string(self).map_err(|e| Error::Parse(e.to_string()))?;
        Ok(format!("{HEADER}{body}"))
    }

    /// Write the register to `path`.
    pub fn save(&self, path: &Path) -> Result<(), Error> {
        self.check()?;
        std::fs::write(path, self.to_text()?).map_err(|e| Error::Io(path.display().to_string(), e))
    }

    /// Every stored κ recomputes, every claim names known corpora and
    /// points, and no question appears twice.
    pub fn check(&self) -> Result<(), Error> {
        let bad = |m: String| Err(Error::Inconsistent(m));
        if self.schema != SCHEMA {
            return bad(format!("schema {} is not {SCHEMA}", self.schema));
        }
        for c in &self.corpus {
            if corpus_kappa(&c.members) != c.kappa {
                return bad(format!("corpus {} κ does not recompute", c.name));
            }
        }
        for p in &self.point {
            if p.point()?.kappa() != p.kappa {
                return bad(format!("point {} κ does not recompute", p.kappa));
            }
        }
        let mut seen = BTreeMap::new();
        for c in &self.claim {
            if claim_kappa(c) != c.id {
                return bad(format!("claim {} κ does not recompute", c.id));
            }
            if seen.insert(c.id.clone(), ()).is_some() {
                return bad(format!("claim {} appears twice", c.id));
            }
            if (c.form == Form::Universal) != c.corpus.is_empty() {
                return bad(format!(
                    "claim {}: exactly the universal claims name no corpus",
                    c.id
                ));
            }
            if c.form == Form::Universal && c.theorem.is_none() {
                return bad(format!("universal claim {} names no theorem", c.id));
            }
            if !c.corpus.is_empty() && self.corpus_by_kappa(&c.corpus).is_none() {
                return bad(format!("claim {} names an unknown corpus", c.id));
            }
            for p in [&c.codec, &c.candidate, &c.incumbent].into_iter().flatten() {
                if !self.point.iter().any(|q| &q.kappa == p) {
                    return bad(format!("claim {} names an unknown point {p}", c.id));
                }
            }
        }
        Ok(())
    }

    /// The corpus called `name`.
    pub fn corpus_named(&self, name: &str) -> Result<&Corpus, Error> {
        self.corpus
            .iter()
            .find(|c| c.name == name)
            .ok_or_else(|| Error::Unknown(format!("corpus {name}")))
    }

    /// The corpus of κ `kappa`.
    pub fn corpus_by_kappa(&self, kappa: &str) -> Option<&Corpus> {
        self.corpus.iter().find(|c| c.kappa == kappa)
    }

    /// The claim of κ `kappa`, when known.
    pub fn known(&self, kappa: &str) -> Option<&Claim> {
        self.claim.iter().find(|c| c.id == kappa)
    }

    /// Record a point (once).
    pub fn add_point(&mut self, point: &CodecPoint, label: Option<&str>) {
        let kappa = point.kappa();
        match self.point.iter_mut().find(|p| p.kappa == kappa) {
            Some(p) => {
                if p.label.is_none() {
                    p.label = label.map(str::to_owned);
                }
            }
            None => self.point.push(point.record(label)),
        }
    }

    /// Record a corpus (once; a second corpus of the same name must be the
    /// same corpus).
    pub fn add_corpus(&mut self, corpus: Corpus) -> Result<(), Error> {
        match self.corpus.iter().find(|c| c.name == corpus.name) {
            Some(c) if c.kappa == corpus.kappa => Ok(()),
            Some(_) => Err(Error::Inconsistent(format!(
                "a different corpus is already called {}",
                corpus.name
            ))),
            None => {
                self.corpus.push(corpus);
                Ok(())
            }
        }
    }

    /// Put `claim` in the register under its κ, replacing an earlier record
    /// of the same question.
    pub fn put(&mut self, mut claim: Claim) -> &Claim {
        claim.id = claim_kappa(&claim);
        let at = match self.claim.iter().position(|c| c.id == claim.id) {
            Some(k) => {
                self.claim[k] = claim;
                k
            }
            None => {
                self.claim.push(claim);
                self.claim.len() - 1
            }
        };
        &self.claim[at]
    }

    /// The closed question for `point` on `corpus`.
    pub fn closed_question(point: &CodecPoint, corpus: &Corpus) -> Claim {
        let mut q = Claim::question(Form::Closed, &corpus.kappa);
        q.codec = Some(point.kappa());
        q.id = claim_kappa(&q);
        q
    }

    /// Decide "point codes corpus in exactly N bytes and S steps".
    ///
    /// A claim the factory decided is returned as recorded and never rerun.
    /// So is one decided locally when `by` is local too. Otherwise the shipped
    /// codec runs over `files` (the corpus members' bytes, in order): a
    /// claim with stated bytes and steps is proved when the run reproduces
    /// them exactly and refuted (keeping what was observed) when it does not;
    /// a claim with none records the run's values, proved by that run.
    pub fn decide(
        &mut self,
        point: &CodecPoint,
        corpus: &Corpus,
        files: &[Vec<u8>],
        by: &str,
    ) -> Result<Closed, Error> {
        let q = Register::closed_question(point, corpus);
        let factory = by.starts_with("factory:");
        if let Some(known) = self.known(&q.id) {
            if known.final_() || (!factory && known.status != Status::Minted) {
                if let Some(mut closed) = known.closed() {
                    // a refuted statement answers with what was observed
                    closed.bytes = known.observed_bytes.unwrap_or(closed.bytes);
                    closed.steps = known.observed_steps.unwrap_or(closed.steps);
                    return Ok(closed);
                }
            }
        }
        self.add_corpus(corpus.clone())?;
        self.add_point(point, None);
        let run = measure(point, corpus, files)?;
        let mut claim = self.known(&q.id).cloned().unwrap_or(q);
        match (claim.bytes, claim.steps) {
            (Some(b), Some(s)) if (b, s) != (run.bytes, run.steps) => {
                claim.status = Status::Refuted;
                claim.observed_bytes = Some(run.bytes);
                claim.observed_steps = Some(run.steps);
            }
            _ => {
                claim.status = Status::Proved;
                claim.bytes = Some(run.bytes);
                claim.steps = Some(run.steps);
                claim.observed_bytes = None;
                claim.observed_steps = None;
            }
        }
        claim.members = run.members.clone();
        claim.receipt = Some(by.to_owned());
        self.put(claim);
        Ok(run)
    }

    /// Decide every bound claim of `point` on `corpus` against the pinned
    /// comparators, from the closed claim (no run): proved when the archive
    /// is no larger than the comparator's.
    pub fn decide_bounds(&mut self, point: &CodecPoint, corpus: &Corpus, by: &str) -> Vec<Claim> {
        let Some(closed) = self
            .known(&Register::closed_question(point, corpus).id)
            .filter(|c| c.status == Status::Proved)
            .and_then(Claim::closed)
        else {
            return Vec::new();
        };
        let comparators: Vec<Comparator> = self
            .comparator
            .iter()
            .filter(|c| c.corpus == corpus.kappa)
            .cloned()
            .collect();
        comparators
            .iter()
            .map(|c| {
                let mut q = Claim::question(Form::Bound, &corpus.kappa);
                q.codec = Some(point.kappa());
                q.against = Some(c.tool.clone());
                q.bound = Some(c.bytes);
                q.status = if closed.bytes <= c.bytes {
                    Status::Proved
                } else {
                    Status::Refuted
                };
                q.receipt = Some(by.to_owned());
                self.put(q).clone()
            })
            .collect()
    }

    /// Decide "candidate dominates incumbent on `family` of `corpus`" from
    /// their closed claims, both of which must be proved; `None` when either
    /// is missing. The result is recorded under its κ.
    pub fn decide_dominance(
        &mut self,
        candidate: &CodecPoint,
        incumbent: &CodecPoint,
        family: Option<&str>,
        corpus: &Corpus,
        by: &str,
    ) -> Option<Claim> {
        let answer = |p: &CodecPoint| {
            self.known(&Register::closed_question(p, corpus).id)
                .filter(|c| c.status == Status::Proved)
                .and_then(Claim::closed)
        };
        let (c, i) = (answer(candidate)?, answer(incumbent)?);
        let mut q = Claim::question(Form::Dominance, &corpus.kappa);
        q.candidate = Some(candidate.kappa());
        q.incumbent = Some(incumbent.kappa());
        q.family = family.map(str::to_owned);
        q.status = if dominates(&c, &i, family) {
            Status::Proved
        } else {
            Status::Refuted
        };
        q.receipt = Some(by.to_owned());
        Some(self.put(q).clone())
    }

    /// Record `point` as excluded on `corpus` (a refuted point, never rerun).
    pub fn exclude(&mut self, point: &CodecPoint, corpus: &Corpus, by: &str) -> Claim {
        self.add_point(point, None);
        let mut q = Claim::question(Form::Exclusion, &corpus.kappa);
        q.codec = Some(point.kappa());
        q.status = Status::Proved;
        q.receipt = Some(by.to_owned());
        self.put(q).clone()
    }

    /// Record `point` as excluded on every corpus by the kernel theorem
    /// `theorem` at `parameter` (a universal claim: no corpus, no run).
    pub fn exclude_universal(
        &mut self,
        point: &CodecPoint,
        theorem: &str,
        parameter: &str,
        by: &str,
    ) -> Claim {
        self.add_point(point, None);
        let mut q = Claim::question(Form::Universal, "");
        q.codec = Some(point.kappa());
        q.theorem = Some(theorem.to_owned());
        q.parameter = Some(parameter.to_owned());
        q.status = Status::Proved;
        q.receipt = Some(by.to_owned());
        self.put(q).clone()
    }

    /// Whether `point` is excluded on `corpus`: by an exclusion on that
    /// corpus, or by a universal claim on any.
    pub fn excluded(&self, point: &CodecPoint, corpus: &Corpus) -> bool {
        let k = point.kappa();
        self.claim.iter().any(|c| {
            c.status == Status::Proved
                && c.codec.as_deref() == Some(k.as_str())
                && (c.form == Form::Universal
                    || (c.form == Form::Exclusion && c.corpus == corpus.kappa))
        })
    }
}

/// Run the codec at `point` over the corpus members `files`: compress each
/// member as its own stream, read the decode steps from the frame headers,
/// and decompress it back. Exact and deterministic: the result depends on
/// the point and the bytes alone (not on the thread count or the machine).
pub fn measure(point: &CodecPoint, corpus: &Corpus, files: &[Vec<u8>]) -> Result<Closed, Error> {
    if point.state.is_some() || point.lanes != 1 {
        return Err(Error::Codec(
            "this client codes fresh models in one lane only".to_owned(),
        ));
    }
    if files.len() != corpus.members.len() {
        return Err(Error::Member(format!(
            "{} files for {} members",
            files.len(),
            corpus.members.len()
        )));
    }
    let threads = uorc::default_threads();
    let mut members = Vec::with_capacity(files.len());
    for (m, input) in corpus.members.iter().zip(files) {
        let fail = |what: &str| Error::Codec(format!("{}: {what}", m.name));
        let stream = point.plan.compress(input, threads);
        let mut steps = 0u64;
        for frame in uorc::frames(&stream).map_err(|e| fail(&format!("frames: {e}")))? {
            let info = uorc::inspect(frame).map_err(|e| fail(&format!("inspect: {e}")))?;
            let s = uorc::performance::frame_steps(&info).ok_or_else(|| {
                fail(&format!(
                    "a {} frame has no step value",
                    info.representation.name()
                ))
            })?;
            steps = steps.checked_add(s).ok_or_else(|| fail("step overflow"))?;
        }
        let back = uorc::decompress(&stream, uorc::DEFAULT_DECODE_WORK)
            .map_err(|e| fail(&format!("decompress: {e}")))?;
        if back != *input {
            return Err(fail("the archive does not round-trip"));
        }
        let head = &input[..input.len().min(uorc::FRAME)];
        members.push(MemberResult {
            name: m.name.clone(),
            family: FAMILIES[portfolio::family(head)].to_owned(),
            bytes: stream.len() as u64,
            steps,
        });
    }
    Ok(Closed {
        bytes: members.iter().map(|m| m.bytes).sum(),
        steps: members.iter().map(|m| m.steps).sum(),
        members,
    })
}

/// The export identity recorded in `generated/rust/factory.identity` under
/// `repo` (its `export <hex>` line).
pub fn export_identity(repo: &Path) -> Result<String, Error> {
    let path = repo.join("generated/rust/factory.identity");
    let text =
        std::fs::read_to_string(&path).map_err(|e| Error::Io(path.display().to_string(), e))?;
    text.lines()
        .find_map(|l| l.strip_prefix("export "))
        .map(|s| s.trim().to_owned())
        .ok_or_else(|| Error::Parse(format!("{} has no export line", path.display())))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tiny_corpus() -> (Corpus, Vec<Vec<u8>>) {
        let files: Vec<Vec<u8>> = vec![
            b"hello hello hello hello".to_vec(),
            (0..20_000u32).map(|i| (i * 7 % 251) as u8).collect(),
            Vec::new(),
        ];
        let members = ["a.txt", "b.bin", "empty"]
            .iter()
            .zip(&files)
            .map(|(n, f)| Member::of(n, f))
            .collect();
        (Corpus::new("tiny", "test", false, members), files)
    }

    #[test]
    fn closed_claims_are_decided_once_and_reproduce() {
        let (corpus, files) = tiny_corpus();
        let point = CodecPoint::shipped("test-export");
        let mut reg = Register::default();
        let first = reg
            .decide(&point, &corpus, &files, "local")
            .expect("decide");
        assert_eq!(first.members.len(), 3);
        assert_eq!(first.members[2].steps, 0);
        // known by κ: a local decision is not rerun locally
        let again = reg.decide(&point, &corpus, &[], "local").expect("known");
        assert_eq!(first, again);
        // the factory re-decides a local result and proves it
        reg.decide(&point, &corpus, &files, "factory:x")
            .expect("factory");
        let claim = reg
            .known(&Register::closed_question(&point, &corpus).id)
            .expect("claim");
        assert_eq!(claim.status, Status::Proved);
        assert!(claim.final_());
        // a wrong stated answer is refuted with the observation kept
        let mut wrong = claim.clone();
        wrong.bytes = Some(first.bytes + 1);
        wrong.status = Status::Minted;
        wrong.receipt = None;
        reg.put(wrong);
        reg.decide(&point, &corpus, &files, "factory:y")
            .expect("refute");
        let claim = reg
            .known(&Register::closed_question(&point, &corpus).id)
            .expect("claim");
        assert_eq!(claim.status, Status::Refuted);
        assert_eq!(claim.observed_bytes, Some(first.bytes));
        // the text form round-trips
        let text = reg.to_text().expect("text");
        assert_eq!(Register::parse(&text).expect("parse"), reg);
    }

    #[test]
    fn the_shipped_plan_is_the_shipped_client() {
        let (corpus, files) = tiny_corpus();
        let run = measure(&CodecPoint::shipped("e"), &corpus, &files).expect("measure");
        for (m, f) in run.members.iter().zip(&files) {
            assert_eq!(
                m.bytes,
                uorc::compress(f, 0).expect("compress").len() as u64
            );
        }
    }

    #[test]
    fn dominance_and_bounds_are_decided_from_closed_claims() {
        let (corpus, files) = tiny_corpus();
        let shipped = CodecPoint::shipped("e");
        let v03 = CodecPoint {
            plan: Plan::Fixed(Strategy {
                x86: false,
                profile: uorc::ncm::V03,
                state: 0,
            }),
            ..shipped.clone()
        };
        let mut reg = Register::default();
        let a = reg.decide(&shipped, &corpus, &files, "local").expect("a");
        let b = reg.decide(&v03, &corpus, &files, "local").expect("b");
        let d = reg
            .decide_dominance(&v03, &shipped, None, &corpus, "local")
            .expect("both known");
        assert_eq!(d.status == Status::Proved, dominates(&b, &a, None));
        reg.comparator.push(Comparator {
            corpus: corpus.kappa.clone(),
            tool: "none".to_owned(),
            version: "-".to_owned(),
            bytes: a.bytes,
            source: "test".to_owned(),
        });
        let bounds = reg.decide_bounds(&shipped, &corpus, "local");
        assert_eq!(bounds.len(), 1);
        assert_eq!(bounds[0].status, Status::Proved);
        reg.check().expect("consistent");
        assert!(!reg.excluded(&v03, &corpus));
        let u = reg.exclude_universal(&v03, "Uorc.Performance.dominated", "0x1ffff", "local");
        assert!(u.corpus.is_empty());
        assert!(reg.excluded(&v03, &corpus));
        let text = reg.to_text().expect("text");
        assert_eq!(Register::parse(&text).expect("parse"), reg);
    }

    #[test]
    fn steps_follow_the_measure() {
        let (corpus, files) = tiny_corpus();
        let run = measure(&CodecPoint::shipped("e"), &corpus, &files).expect("measure");
        let stream = uorc::compress(&files[1], 0).expect("compress");
        let info = uorc::inspect(uorc::frames(&stream).expect("frames")[0]).expect("inspect");
        let per_byte = run.members[1].steps / files[1].len() as u64;
        assert!(matches!(
            info.representation,
            uorc::Representation::Ncm | uorc::Representation::Raw
        ));
        assert!(per_byte == 1 || per_byte.is_multiple_of(8));
    }

    #[test]
    fn the_repository_register_is_consistent() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../frontier.toml");
        let reg = Register::load(&path).expect("frontier.toml loads and checks");
        let text = std::fs::read_to_string(&path).expect("read");
        assert_eq!(
            reg.to_text().expect("text"),
            text,
            "frontier.toml is in canonical form"
        );
    }
}
